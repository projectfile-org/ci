// TestQuietFlag pins -q and -quiet on every subcommand.
func TestQuietFlag(t *testing.T) {
	for name := range commands {
		for _, flagName := range []string{"-q", "-quiet"} {
			fs, o, _ := newFlagSet(name)
			if err := fs.Parse([]string{flagName}); err != nil || !o.quiet {
				t.Fatalf("%s %s: quiet=%v err=%v, want quiet", name, flagName, o.quiet, err)
			}
		}
	}
}

// TestDashProjectfileReadsStdin pins `-pf -`: the document comes from stdin and its staging file is gone after the run.
func TestDashProjectfileReadsStdin(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	for _, tc := range []struct {
		doc  string
		code int
	}{{"name: demo\n", 0}, {"name: [unclosed\n", 1}} {
		var stdout, stderr bytes.Buffer
		if code := run([]string{"resolve", "-pf", "-"}, strings.NewReader(tc.doc), &stdout, &stderr); code != tc.code {
			t.Fatalf("doc %q: exit %d, want %d (stderr=%q)", tc.doc, code, tc.code, stderr.String())
		}
		if left, _ := os.ReadDir(dir); len(left) != 0 {
			t.Fatalf("doc %q: staging file left behind: %v", tc.doc, left)
		}
	}
}

// TestDashOutputRefused pins `-o -`: a usage error, and no directory named - is ever created.
func TestDashOutputRefused(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	var stdout, stderr bytes.Buffer
	if code := run([]string{"generate", "-target", "gha", "-o", "-"}, nil, &stdout, &stderr); code != 2 {
		t.Fatalf("exit %d, want 2 (stderr=%q)", code, stderr.String())
	}
	if err := writeWorkflow(filepath.Join("-", "build.yaml"), []byte("x")); err == nil {
		t.Fatal("writeWorkflow: got nil error for a - path element")
	}
	if _, err := os.Stat(filepath.Join(dir, "-")); !os.IsNotExist(err) {
		t.Fatalf("a directory named - exists (err=%v)", err)
	}
}

// TestWriteWorkflowDirDryRunAndNoForce pins -dry-run (plan on stdout, nothing touched) and -force=false (orphan kept, run fails naming -force).
func TestWriteWorkflowDirDryRunAndNoForce(t *testing.T) {
	dir := t.TempDir()
	stale := filepath.Join(dir, "published.yaml")
	if err := os.WriteFile(stale, []byte("# Generated by pf-ci\nname: published\n"), 0o644); err != nil {
		t.Fatalf("seed stale file: %v", err)
	}
	fresh := filepath.Join(dir, "build.yaml")
	files := map[string][]byte{fresh: []byte("name: build\n")}
	var plan bytes.Buffer
	if err := writeWorkflowDir(dir, ".yaml", files, true, true, &plan); err != nil {
		t.Fatalf("dry run: %v", err)
	}
	if want := "write " + fresh + "\nremove " + stale + "\n"; plan.String() != want {
		t.Fatalf("dry run plan %q, want %q", plan.String(), want)
	}
	if _, err := os.Stat(fresh); !os.IsNotExist(err) {
		t.Fatalf("dry run wrote %s (err=%v)", fresh, err)
	}
	err := writeWorkflowDir(dir, ".yaml", files, false, false, io.Discard)
	if err == nil || !strings.Contains(err.Error(), "-force") {
		t.Fatalf("no-force run: err=%v, want one naming -force", err)
	}
	if _, err := os.Stat(stale); err != nil {
		t.Fatalf("no-force run removed the orphan: %v", err)
	}
}
