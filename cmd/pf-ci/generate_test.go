// TestGenerateLefthookWritesAndChecks pins the git-hook lowering: one file (not a
// directory) carrying a hook per HookStages node, then a passing -check.
func TestGenerateLefthookWritesAndChecks(t *testing.T) {
	const doc = `identity:
  name: demo
  version: 1.0.0
  released: "2026-01-01"
org:
  projectfile:
    ci:
      image: demo/app
      tools:
        shellcheck:
          run: shellcheck
      nodes:
        pre-commit:
          needs: {shellcheck: true}
        pre-push:
          needs: {shellcheck: true}
`
	dir := t.TempDir()
	path := filepath.Join(dir, "lefthook.yaml")
	pf := demoDoc(t, doc)
	var stdout, stderr bytes.Buffer
	args := []string{subGenerate, flagTarget, render.TargetLefthook, flagPf, pf, "-o", path}
	if code := run(args, nil, &stdout, &stderr); code != 0 {
		t.Fatalf("generate lefthook: exit %d (stderr=%q)", code, stderr.String())
	}
	data, err := os.ReadFile(path) // #nosec G304 — a temp path the test itself built
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	for _, hook := range []string{"pre-commit", "pre-push"} {
		if !strings.Contains(string(data), hook) {
			t.Fatalf("%s lacks the %s hook:\n%s", path, hook, data)
		}
	}
	var stdout2, stderr2 bytes.Buffer
	if code := run(append(args, flagCheck), nil, &stdout2, &stderr2); code != 0 {
		t.Fatalf("lefthook -check: exit %d, want 0 (stderr=%q)", code, stderr2.String())
	}
}

