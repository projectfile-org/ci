// goalDoc is a projectfile declaring ONE explicit goal over a two-step DAG, the
// minimal shape per-goal generation needs.
const goalDoc = `identity:
  name: demo
  version: 1.2.3
  released: "2026-01-01"
org:
  projectfile:
    ci:
      image: demo/app
      targets: [gha]
      tools:
        container-build:
          run: make container-build
      nodes:
        source-is-valid:
          needs: {shellcheck: true}
        image-built:
          matrix: true
          needs: {source-is-valid: true, container-build: true}
        ready:
          goal: true
          needs: {image-built: true}
`

// TestGenerateWritesOneFilePerGoal pins the per-goal lowering end to end: `ready`
// renders to <dir>/ready.yaml, the header banner marks it generated (so a later
// orphan sweep recognises it), and the run reports success.
func TestGenerateWritesOneFilePerGoal(t *testing.T) {
	out := t.TempDir()
	pf := demoDoc(t, goalDoc)
	var stdout, stderr bytes.Buffer
	code := run([]string{subGenerate, flagTarget, targetGHA, flagPf, pf, "-o", out}, nil, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("generate: exit %d, want 0 (stderr=%q)", code, stderr.String())
	}
	path := filepath.Join(out, "ready.yaml")
	data, err := os.ReadFile(path) // #nosec G304 — a temp path the test itself built
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	if !strings.Contains(string(data), generatedMarker) {
		t.Fatalf("%s lacks the %q banner", path, generatedMarker)
	}
	if !strings.Contains(string(data), "image-built") {
		t.Fatalf("%s lost the closure node it must contain:\n%s", path, data)
	}
}

