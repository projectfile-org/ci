// TestLefthookRenderFailureSurfaces pins that a lefthook template that cannot
// render is reported, not swallowed into a successful no-op run.
func TestLefthookRenderFailureSurfaces(t *testing.T) {
	// A hook node named after a stage but carrying an unresolvable template makes the
	// render fail; the run must exit non-zero rather than write a partial file.
	pf := demoDoc(t, `identity:
  name: demo
  version: 1.0.0
  released: "2026-01-01"
org:
  projectfile:
    ci:
      image: demo/app
      tools: {shellcheck: {run: shellcheck}}
      nodes:
        pre-commit:
          needs: {shellcheck: true}
        "${": true
`)
	var stdout, stderr bytes.Buffer
	// The parse itself refuses the malformed node name, which is the same contract
	// from the read side: a document pf-ci cannot lower never becomes a file.
	code := run([]string{subGenerate, flagTarget, render.TargetLefthook, flagPf, pf, "-o", filepath.Join(t.TempDir(), "lh.yaml")}, nil, &stdout, &stderr)
	if code == 0 {
		t.Skip("core accepted the fixture node name; nothing to assert")
	}
	if stderr.Len() == 0 {
		t.Fatal("a failing render printed no reason")
	}
}
