// TestGenerateCheckReportsDrift pins that -check fails when a committed workflow
// no longer matches the DAG, naming the file as stale — the gate `make ci-check`
// rides on.
func TestGenerateCheckReportsDrift(t *testing.T) {
	out := t.TempDir()
	path := filepath.Join(out, "ready.yaml")
	if err := os.WriteFile(path, []byte("# Generated by pf-ci\nname: ready\nstale: true\n"), 0o600); err != nil {
		t.Fatalf("seed: %v", err)
	}
	var stdout, stderr bytes.Buffer
	code := run([]string{subGenerate, flagTarget, targetGHA, flagPf, demoDoc(t, goalDoc), "-o", out, flagCheck}, nil, &stdout, &stderr)
	if code != 3 {
		t.Fatalf("exit %d, want 3 (stderr=%q)", code, stderr.String())
	}
	if !strings.Contains(stderr.String(), "is stale") || !strings.Contains(stderr.String(), "ready.yaml") {
		t.Fatalf("stderr %q does not name the stale file", stderr.String())
	}
}

